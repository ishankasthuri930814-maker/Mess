package com.example.util

import android.content.Context
import android.content.Intent
import android.graphics.Color
import android.graphics.Paint
import android.graphics.Typeface
import android.graphics.pdf.PdfDocument
import android.net.Uri
import androidx.core.content.FileProvider
import com.example.data.DutyRecord
import com.example.data.MessRecord
import com.example.data.OfficerProfile
import com.example.data.RunningChartRecord
import java.io.File
import java.io.FileOutputStream

object ReportGenerator {

    data class ReportData(
        val startDate: String,
        val endDate: String,
        val profile: OfficerProfile?,
        val dutyRecords: List<DutyRecord>,
        val messRecords: List<MessRecord>,
        val runningChartRecords: List<RunningChartRecord>,
        val bDefaultPrice: Double = 150.0,
        val lDefaultPrice: Double = 220.0,
        val dDefaultPrice: Double = 180.0
    )

    fun generateTextSummary(data: ReportData): String {
        val officerName = if (data.profile != null) "${data.profile.rank} ${data.profile.name}".trim() else "නිලධාරියා"
        val badge = if (data.profile?.badgeNumber?.isNotBlank() == true) data.profile.badgeNumber else "-"
        val station = if (data.profile?.station?.isNotBlank() == true) data.profile.station else "-"

        // Duty Calculations
        val dutyHoursMins = calculateTotalDutyMins(data.dutyRecords)
        val onDutyCount = data.dutyRecords.count { it.type == "ON_DUTY" }
        val offDutyCount = data.dutyRecords.count { it.type == "OFF_DUTY" }
        val extraDutyCount = data.dutyRecords.count { it.type == "EXTRA_DUTY" }

        // Mess Calculations
        val takenMeals = data.messRecords.filter { it.isTaken }
        val bCount = takenMeals.count { it.mealType == "BREAKFAST" }
        val lCount = takenMeals.count { it.mealType == "LUNCH" }
        val dCount = takenMeals.count { it.mealType == "DINNER" }
        val totalMessCost = takenMeals.sumOf { r ->
            if (r.price > 0.0) r.price else when (r.mealType) {
                "BREAKFAST" -> data.bDefaultPrice
                "LUNCH" -> data.lDefaultPrice
                "DINNER" -> data.dDefaultPrice
                else -> 180.0
            }
        }

        // Running Chart Calculations
        val totalDistance = data.runningChartRecords.sumOf { it.distanceKm }
        val totalFuelConsumed = data.runningChartRecords.sumOf { it.consumedFuel }
        val vehiclesUsed = data.runningChartRecords.map { it.vehicleNumber }.distinct()

        val sb = StringBuilder()
        sb.appendLine("🇱🇰 *ශ්‍රී ලංකා පොලීසිය - All In One Police*")
        sb.appendLine("📋 *සම්පූර්ණ රාජකාරි සහ මෙස් වාර්තා සාරාංශය*")
        sb.appendLine("----------------------------------------")
        sb.appendLine("📅 *කාල සීමාව:* ${data.startDate} සිට ${data.endDate} දක්වා")
        sb.appendLine("👮 *නිලධාරියා:* $officerName (අංකය: $badge)")
        sb.appendLine("🏢 *පොලිස් ස්ථානය:* $station")
        sb.appendLine()
        sb.appendLine("👮‍♂️ *රාජකාරි සාරාංශය (Duty Summary):*")
        sb.appendLine("• මුළු රාජකාරි කාලය: ${dutyHoursMins.first} පැය ${dutyHoursMins.second} මිනි")
        sb.appendLine("• රාජකාරියට වාර්තා කිරීම් (On Duty): $onDutyCount")
        sb.appendLine("• බැහැරවීම් (Off Duty): $offDutyCount")
        sb.appendLine("• අමතර රාජකාරි (Extra Duty): $extraDutyCount")
        sb.appendLine("• මුළු රාජකාරි සටහන් ගණන: ${data.dutyRecords.size}")
        sb.appendLine()
        sb.appendLine("🍽️ *මෙස් ආහාර සහ වියදම් සාරාංශය (Mess Expenditure):*")
        sb.appendLine("• ලබාගත් මුළු ආහාර වේල්: ${takenMeals.size}")
        sb.appendLine("• උදේ: $bCount | දිවා: $lCount | රාත්‍රී: $dCount")
        sb.appendLine("• මෙතෙක් මුළු මෙස් වියදම: රු. ${"%.2f".format(totalMessCost)}")
        sb.appendLine()
        sb.appendLine("🚘 *වාහන ගමන් සටහන් (Running Chart):*")
        sb.appendLine("• ධාවනය කළ මුළු දුර: ${"%.1f".format(totalDistance)} km")
        sb.appendLine("• භාවිත කළ ඉන්ධන: ${"%.1f".format(totalFuelConsumed)} Liters")
        if (vehiclesUsed.isNotEmpty()) {
            sb.appendLine("• වාහන අංක: ${vehiclesUsed.joinToString(", ")}")
        }
        sb.appendLine("----------------------------------------")
        sb.appendLine("Generated by All In One Police App")
        return sb.toString()
    }

    private fun calculateTotalDutyMins(records: List<DutyRecord>): Pair<Long, Long> {
        val totalMins = records.sumOf { it.dutyDurationMinutes }
        val hours = totalMins / 60
        val mins = totalMins % 60
        return Pair(hours, mins)
    }

    fun createPdfReport(context: Context, data: ReportData): File {
        val pdfDocument = PdfDocument()
        val pageWidth = 595 // A4 standard width points
        val pageHeight = 842 // A4 standard height points

        var pageNumber = 1
        var pageInfo = PdfDocument.PageInfo.Builder(pageWidth, pageHeight, pageNumber).create()
        var page = pdfDocument.startPage(pageInfo)
        var canvas = page.canvas

        val paint = Paint().apply { isAntiAlias = true }
        var y = 40f

        fun checkPageOverflow(requiredHeight: Float) {
            if (y + requiredHeight > pageHeight - 50f) {
                pdfDocument.finishPage(page)
                pageNumber++
                pageInfo = PdfDocument.PageInfo.Builder(pageWidth, pageHeight, pageNumber).create()
                page = pdfDocument.startPage(pageInfo)
                canvas = page.canvas
                y = 40f
            }
        }

        // --- Header Section ---
        paint.color = Color.parseColor("#1B2A4A") // Police Navy
        canvas.drawRect(20f, y, pageWidth - 20f, y + 65f, paint)

        paint.color = Color.parseColor("#FFD700") // Badge Gold
        paint.textSize = 18f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        canvas.drawText("ALL IN ONE POLICE - FULL SUMMARY REPORT", 35f, y + 28f, paint)

        paint.color = Color.WHITE
        paint.textSize = 11f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
        canvas.drawText("Sri Lanka Police • Duty, Mess Expenditure & Running Chart Summary", 35f, y + 48f, paint)

        y += 80f

        // --- Officer & Date Range Info Box ---
        paint.color = Color.parseColor("#F1F5F9")
        canvas.drawRoundRect(20f, y, pageWidth - 20f, y + 70f, 12f, 12f, paint)

        paint.color = Color.parseColor("#0F172A")
        paint.textSize = 12f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)

        val officerName = if (data.profile != null) "${data.profile.rank} ${data.profile.name}".trim() else "Officer"
        val badge = if (data.profile?.badgeNumber?.isNotBlank() == true) data.profile.badgeNumber else "-"
        val station = if (data.profile?.station?.isNotBlank() == true) data.profile.station else "-"

        canvas.drawText("Officer: $officerName (No: $badge)", 35f, y + 25f, paint)
        canvas.drawText("Station: $station", 35f, y + 48f, paint)

        paint.color = Color.parseColor("#1E3A8A")
        canvas.drawText("Date Range: ${data.startDate}  to  ${data.endDate}", 320f, y + 25f, paint)
        paint.color = Color.parseColor("#475569")
        paint.textSize = 10f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
        canvas.drawText("Generated Date: ${DateTimeUtils.formatDate(System.currentTimeMillis())}", 320f, y + 48f, paint)

        y += 85f

        // --- SECTION 1: DUTY SUMMARY ---
        checkPageOverflow(120f)

        paint.color = Color.parseColor("#1E3A8A")
        paint.textSize = 14f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        canvas.drawText("1. DUTY SUMMARY & LOGS", 25f, y, paint)
        paint.strokeWidth = 1.5f
        canvas.drawLine(25f, y + 4f, pageWidth - 25f, y + 4f, paint)

        y += 20f

        val (hours, mins) = calculateTotalDutyMins(data.dutyRecords)
        val onDutyCount = data.dutyRecords.count { it.type == "ON_DUTY" }
        val offDutyCount = data.dutyRecords.count { it.type == "OFF_DUTY" }
        val extraDutyCount = data.dutyRecords.count { it.type == "EXTRA_DUTY" }

        // Duty Stats Cards
        paint.color = Color.parseColor("#EFF6FF")
        canvas.drawRoundRect(25f, y, pageWidth - 25f, y + 45f, 8f, 8f, paint)

        paint.color = Color.parseColor("#1E40AF")
        paint.textSize = 11f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        canvas.drawText("Total Duty Duration: $hours Hours $mins Minutes", 35f, y + 26f, paint)
        canvas.drawText("On Duty: $onDutyCount   |   Off Duty: $offDutyCount   |   Extra Duty: $extraDutyCount", 280f, y + 26f, paint)

        y += 60f

        // Duty Log Table Header
        paint.color = Color.parseColor("#CBD5E1")
        canvas.drawRect(25f, y, pageWidth - 25f, y + 20f, paint)
        paint.color = Color.parseColor("#0F172A")
        paint.textSize = 10f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        canvas.drawText("Date & Time", 30f, y + 14f, paint)
        canvas.drawText("Type", 150f, y + 14f, paint)
        canvas.drawText("IB Page / Para", 240f, y + 14f, paint)
        canvas.drawText("Duty Nature / Remarks", 350f, y + 14f, paint)

        y += 22f

        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
        paint.textSize = 9.5f

        if (data.dutyRecords.isEmpty()) {
            paint.color = Color.GRAY
            canvas.drawText("No duty records found for selected date range.", 30f, y + 15f, paint)
            y += 25f
        } else {
            data.dutyRecords.take(25).forEach { r ->
                checkPageOverflow(25f)
                val typeLabel = when (r.type) {
                    "ON_DUTY" -> "ON DUTY"
                    "OFF_DUTY" -> "OFF DUTY"
                    else -> "EXTRA DUTY"
                }
                val pagePara = if (r.ibPage.isNotBlank()) "P: ${r.ibPage} / ¶: ${r.ibParagraph}" else "-"
                val details = (if (r.dutyNature.isNotBlank()) r.dutyNature else r.remarks).take(30)
                val timeStr = DateTimeUtils.formatFullDateTime(r.timestamp)

                paint.color = Color.parseColor("#334155")
                canvas.drawText(timeStr, 30f, y + 14f, paint)
                paint.color = if (r.type == "ON_DUTY") Color.parseColor("#166534") else Color.parseColor("#9A3412")
                canvas.drawText(typeLabel, 150f, y + 14f, paint)
                paint.color = Color.parseColor("#334155")
                canvas.drawText(pagePara, 240f, y + 14f, paint)
                canvas.drawText(details, 350f, y + 14f, paint)

                y += 20f
            }
            if (data.dutyRecords.size > 25) {
                paint.color = Color.GRAY
                canvas.drawText("+ ${data.dutyRecords.size - 25} more duty records...", 30f, y + 12f, paint)
                y += 20f
            }
        }

        y += 15f

        // --- SECTION 2: MESS EXPENDITURE ---
        checkPageOverflow(120f)

        paint.color = Color.parseColor("#1E3A8A")
        paint.textSize = 14f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        canvas.drawText("2. POLICE MESS EXPENDITURE & MEALS", 25f, y, paint)
        paint.strokeWidth = 1.5f
        canvas.drawLine(25f, y + 4f, pageWidth - 25f, y + 4f, paint)

        y += 20f

        val takenMeals = data.messRecords.filter { it.isTaken }
        val bCount = takenMeals.count { it.mealType == "BREAKFAST" }
        val lCount = takenMeals.count { it.mealType == "LUNCH" }
        val dCount = takenMeals.count { it.mealType == "DINNER" }

        val totalMessCost = takenMeals.sumOf { r ->
            if (r.price > 0.0) r.price else when (r.mealType) {
                "BREAKFAST" -> data.bDefaultPrice
                "LUNCH" -> data.lDefaultPrice
                "DINNER" -> data.dDefaultPrice
                else -> 180.0
            }
        }

        // Mess Stats Box
        paint.color = Color.parseColor("#FEF3C7")
        canvas.drawRoundRect(25f, y, pageWidth - 25f, y + 45f, 8f, 8f, paint)

        paint.color = Color.parseColor("#92400E")
        paint.textSize = 11f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        canvas.drawText("Total Meals Taken: ${takenMeals.size}  (Breakfast: $bCount, Lunch: $lCount, Dinner: $dCount)", 35f, y + 26f, paint)
        paint.color = Color.parseColor("#B45309")
        canvas.drawText("Total Mess Expenditure: LKR ${"%.2f".format(totalMessCost)}", 330f, y + 26f, paint)

        y += 60f

        // --- SECTION 3: VEHICLE RUNNING CHART ---
        checkPageOverflow(100f)

        paint.color = Color.parseColor("#1E3A8A")
        paint.textSize = 14f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        canvas.drawText("3. VEHICLE RUNNING CHART SUMMARY", 25f, y, paint)
        paint.strokeWidth = 1.5f
        canvas.drawLine(25f, y + 4f, pageWidth - 25f, y + 4f, paint)

        y += 20f

        val totalDist = data.runningChartRecords.sumOf { it.distanceKm }
        val totalFuel = data.runningChartRecords.sumOf { it.consumedFuel }
        val vehicles = data.runningChartRecords.map { it.vehicleNumber }.distinct()

        paint.color = Color.parseColor("#F1F5F9")
        canvas.drawRoundRect(25f, y, pageWidth - 25f, y + 45f, 8f, 8f, paint)

        paint.color = Color.parseColor("#0F172A")
        paint.textSize = 11f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        canvas.drawText("Total Distance Traveled: ${"%.1f".format(totalDist)} km", 35f, y + 26f, paint)
        canvas.drawText("Fuel Consumed: ${"%.1f".format(totalFuel)} L", 240f, y + 26f, paint)
        canvas.drawText("Vehicles: ${vehicles.joinToString(", ").ifBlank { "-" }}", 380f, y + 26f, paint)

        y += 65f

        // Footer Signoff Box
        checkPageOverflow(50f)
        paint.color = Color.parseColor("#E2E8F0")
        canvas.drawLine(25f, y, pageWidth - 25f, y, paint)

        paint.color = Color.GRAY
        paint.textSize = 9f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.ITALIC)
        canvas.drawText("Certified correct by Officer: $officerName | Official Sri Lanka Police All In One App", 25f, y + 20f, paint)

        pdfDocument.finishPage(page)

        val file = File(context.cacheDir, "Police_Report_${data.startDate}_to_${data.endDate}.pdf")
        FileOutputStream(file).use { out ->
            pdfDocument.writeTo(out)
        }
        pdfDocument.close()
        return file
    }

    fun sharePdfReport(context: Context, pdfFile: File, title: String) {
        val contentUri: Uri = FileProvider.getUriForFile(
            context,
            "${context.packageName}.fileprovider",
            pdfFile
        )

        val shareIntent = Intent(Intent.ACTION_SEND).apply {
            type = "application/pdf"
            putExtra(Intent.EXTRA_STREAM, contentUri)
            putExtra(Intent.EXTRA_SUBJECT, title)
            putExtra(Intent.EXTRA_TEXT, "$title\n\nGenerated using All In One Police App")
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }

        context.startActivity(Intent.createChooser(shareIntent, "PDF වාර්තාව බෙදාගන්න (Share PDF)"))
    }

    fun shareWhatsAppText(context: Context, text: String) {
        val intent = Intent(Intent.ACTION_SEND).apply {
            type = "text/plain"
            putExtra(Intent.EXTRA_TEXT, text)
            setPackage("com.whatsapp")
        }

        try {
            context.startActivity(intent)
        } catch (e: Exception) {
            val chooser = Intent.createChooser(
                Intent(Intent.ACTION_SEND).apply {
                    type = "text/plain"
                    putExtra(Intent.EXTRA_TEXT, text)
                },
                "සාරාංශය බෙදාගන්න (Share Summary)"
            )
            context.startActivity(chooser)
        }
    }

    fun openPdfViewer(context: Context, pdfFile: File) {
        val contentUri: Uri = FileProvider.getUriForFile(
            context,
            "${context.packageName}.fileprovider",
            pdfFile
        )

        val viewIntent = Intent(Intent.ACTION_VIEW).apply {
            setDataAndType(contentUri, "application/pdf")
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }

        try {
            context.startActivity(Intent.createChooser(viewIntent, "PDF පරීක්ෂා කරන්න (View PDF)"))
        } catch (e: Exception) {
            sharePdfReport(context, pdfFile, "Police Report PDF")
        }
    }
}
